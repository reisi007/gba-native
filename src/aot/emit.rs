use std::fmt::Write as _;

use super::artifact::{AotArtifact, AotBlock};
use super::emit_driver::emit_driver;
use crate::cart::Cartridge;
use crate::error::{Error, Result};
use crate::ir::{Cond, IrInstr, Op, PsrSrc, Src};

/// Emit a self-contained Rust harness. Known blocks become direct statements;
/// only unknown targets call the reference interpreter.
pub fn emit_native_module(cart: &Cartridge, artifact: &AotArtifact, budget: u64) -> Result<String> {
    artifact.verify(cart)?;
    if artifact.entry_thumb && !artifact.entry.is_multiple_of(2) {
        return Err(Error::Aot("unaligned Thumb entry".to_string()));
    }
    let mut out = String::new();
    writeln!(
        out,
        "// Generated by gba-native. Experimental prototype; do not edit."
    )
    .unwrap();
    writeln!(
        out,
        "#![allow(clippy::all, unused_variables, unreachable_code)]"
    )
    .unwrap();
    writeln!(out, "use gba_native::bus::Bus;").unwrap();
    writeln!(out, "use gba_native::cart::Cartridge;").unwrap();
    writeln!(out, "use gba_native::cpu::Cpu;").unwrap();
    writeln!(out, "use gba_native::display;").unwrap();
    writeln!(out, "use gba_native::error::{{Error, Result}};").unwrap();
    writeln!(out, "use gba_native::interpret;").unwrap();
    writeln!(out, "use gba_native::ir::Cond;").unwrap();
    writeln!(out, "use gba_native::sha256;").unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "const ROM_SHA256: &str = \"{}\";",
        artifact.rom_sha256_hex()
    )
    .unwrap();
    writeln!(out, "const ENTRY: u32 = 0x{:08X};", artifact.entry).unwrap();
    writeln!(out, "const ENTRY_THUMB: bool = {};", artifact.entry_thumb).unwrap();
    writeln!(out, "const BUDGET: u64 = {budget};").unwrap();
    // The artifact binds the ROM by digest and length only. The generated
    // source deliberately contains no ROM byte array and no raw copy of the
    // input image; the runtime reads a caller-supplied path.
    writeln!(out, "const ROM_LEN: usize = {};", artifact.rom_len).unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#[derive(Clone, Copy, PartialEq, Eq)]").unwrap();
    writeln!(out, "enum Next {{ Continue, Halt }}").unwrap();
    writeln!(out).unwrap();

    for block in &artifact.blocks {
        emit_block(&mut out, block)?;
    }
    emit_driver(&mut out, artifact)?;
    Ok(out)
}

fn emit_block(out: &mut String, block: &AotBlock) -> Result<()> {
    let name = block_name(block.addr, block.thumb);
    writeln!(
        out,
        "fn {name}(cpu: &mut Cpu, bus: &mut Bus, budget: &mut u64) -> Result<Next> {{"
    )
    .unwrap();
    for instruction in &block.instructions {
        writeln!(
            out,
            "    // 0x{:08X} {} 0x{:0width$X}",
            instruction.addr,
            if instruction.thumb { "thumb" } else { "arm" },
            instruction.raw,
            width = if instruction.thumb { 4 } else { 8 }
        )
        .unwrap();
        emit_instruction(out, instruction)?;
    }
    writeln!(out, "    Ok(Next::Continue)").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
    Ok(())
}

fn emit_instruction(out: &mut String, instruction: &IrInstr) -> Result<()> {
    match instruction.op {
        Op::B { target } => {
            if instruction.cond == Cond::Al {
                writeln!(out, "    cpu.set_reg(15, 0x{target:08X});").unwrap();
            } else {
                writeln!(out, "    if {} {{", condition_expression(instruction.cond)).unwrap();
                writeln!(out, "        cpu.set_reg(15, 0x{target:08X});").unwrap();
                writeln!(out, "    }} else {{").unwrap();
                writeln!(
                    out,
                    "        cpu.set_reg(15, 0x{:08X});",
                    instruction.next_addr()
                )
                .unwrap();
                writeln!(out, "    }}").unwrap();
            }
            emit_tick(out, "    ");
            writeln!(out, "    return Ok(Next::Continue);").unwrap();
        }
        Op::Bx { rm } => {
            if instruction.cond == Cond::Al {
                writeln!(out, "    let target = cpu.reg({rm});").unwrap();
                writeln!(out, "    cpu.set_thumb(target & 1 != 0);").unwrap();
                writeln!(out, "    cpu.set_reg(15, target & !1);").unwrap();
            } else {
                writeln!(out, "    if {} {{", condition_expression(instruction.cond)).unwrap();
                writeln!(out, "        let target = cpu.reg({rm});").unwrap();
                writeln!(out, "        cpu.set_thumb(target & 1 != 0);").unwrap();
                writeln!(out, "        cpu.set_reg(15, target & !1);").unwrap();
                writeln!(out, "    }} else {{").unwrap();
                writeln!(
                    out,
                    "        cpu.set_reg(15, 0x{:08X});",
                    instruction.next_addr()
                )
                .unwrap();
                writeln!(out, "    }}").unwrap();
            }
            emit_tick(out, "    ");
            writeln!(out, "    return Ok(Next::Continue);").unwrap();
        }
        _ => {
            let body = instruction_body(instruction);
            if instruction.cond == Cond::Al {
                out.push_str(&body);
            } else {
                writeln!(out, "    if {} {{", condition_expression(instruction.cond)).unwrap();
                out.push_str(&indent(&body, 4));
                writeln!(out, "    }}").unwrap();
            }
            writeln!(
                out,
                "    cpu.set_reg(15, 0x{:08X});",
                instruction.next_addr()
            )
            .unwrap();
            emit_tick(out, "    ");
        }
    }
    Ok(())
}

fn instruction_body(instruction: &IrInstr) -> String {
    let mut out = String::new();
    match instruction.op {
        Op::Mrs { rd, psr } => {
            writeln!(
                out,
                "    let value = cpu.read_psr(gba_native::ir::Psr::{})?;",
                psr.rust_name()
            )
            .unwrap();
            writeln!(out, "    cpu.set_reg({rd}, value);").unwrap();
        }
        Op::Msr { psr, fields, src } => {
            writeln!(
                out,
                "    cpu.write_psr(gba_native::ir::Psr::{}, 0x{fields:02X}, {})?;",
                psr.rust_name(),
                psr_source_expression(src)
            )
            .unwrap();
        }
        Op::Mov { rd, src, set_flags } => {
            writeln!(out, "    let value = {};", source_expression(src)).unwrap();
            writeln!(out, "    cpu.set_reg({rd}, value);").unwrap();
            if set_flags {
                writeln!(
                    out,
                    "    cpu.set_logic_flags(value, {});",
                    carry_expression(src)
                )
                .unwrap();
            }
        }
        Op::Add {
            rd,
            rn,
            rhs,
            set_flags,
        } => {
            writeln!(
                out,
                "    let (result, carry, overflow) = gba_native::cpu::add_flags(cpu.reg({rn}), {});",
                source_expression(rhs)
            )
            .unwrap();
            writeln!(out, "    cpu.set_reg({rd}, result);").unwrap();
            if set_flags {
                writeln!(out, "    cpu.set_arith_flags(result, carry, overflow);").unwrap();
            }
        }
        Op::Sub {
            rd,
            rn,
            rhs,
            set_flags,
        } => {
            writeln!(
                out,
                "    let (result, carry, overflow) = gba_native::cpu::sub_flags(cpu.reg({rn}), {});",
                source_expression(rhs)
            )
            .unwrap();
            writeln!(out, "    cpu.set_reg({rd}, result);").unwrap();
            if set_flags {
                writeln!(out, "    cpu.set_arith_flags(result, carry, overflow);").unwrap();
            }
        }
        Op::Cmp { rn, rhs } => {
            writeln!(
                out,
                "    let (result, carry, overflow) = gba_native::cpu::sub_flags(cpu.reg({rn}), {});",
                source_expression(rhs)
            )
            .unwrap();
            writeln!(out, "    cpu.set_arith_flags(result, carry, overflow);").unwrap();
        }
        Op::LdrLiteral { rd, addr } => {
            writeln!(out, "    let address = 0x{addr:08X}u32;").unwrap();
            writeln!(out, "    let word = bus.read32(address & !3)?;").unwrap();
            writeln!(
                out,
                "    cpu.set_reg({rd}, word.rotate_right((address & 3) * 8));"
            )
            .unwrap();
        }
        Op::LdrHalf { rd, rn, offset } => {
            writeln!(
                out,
                "    let address = cpu.reg({rn}).wrapping_add(0x{:08X}u32);",
                offset as u32
            )
            .unwrap();
            writeln!(out, "    let half = bus.read16(address & !1)? as u32;").unwrap();
            writeln!(
                out,
                "    cpu.set_reg({rd}, if address & 1 != 0 {{ half.rotate_right(8) }} else {{ half }});"
            )
            .unwrap();
        }
        Op::StrHalf { rd, rn, offset } => {
            writeln!(
                out,
                "    let address = cpu.reg({rn}).wrapping_add(0x{:08X}u32);",
                offset as u32
            )
            .unwrap();
            writeln!(out, "    bus.write16(address & !1, cpu.reg({rd}) as u16)?;").unwrap();
        }
        Op::B { .. } | Op::Bx { .. } => unreachable!(),
    }
    out
}

fn source_expression(src: Src) -> String {
    match src {
        Src::Reg(index) => format!("cpu.reg({index})"),
        Src::Imm { value, .. } => format!("0x{value:08X}u32"),
    }
}

fn psr_source_expression(src: PsrSrc) -> String {
    match src {
        PsrSrc::Reg(index) => format!("cpu.reg({index})"),
        PsrSrc::Imm(value) => format!("0x{value:08X}u32"),
    }
}

fn carry_expression(src: Src) -> &'static str {
    match src {
        Src::Reg(_) => "None",
        Src::Imm {
            carry: Some(true), ..
        } => "Some(true)",
        Src::Imm {
            carry: Some(false), ..
        } => "Some(false)",
        Src::Imm { carry: None, .. } => "None",
    }
}

fn condition_expression(cond: Cond) -> String {
    format!(
        "gba_native::cpu::condition_holds(cpu.cpsr(), Cond::{})",
        cond.name()
    )
}

fn emit_tick(out: &mut String, indent: &str) {
    writeln!(out, "{indent}*budget -= 1;").unwrap();
    writeln!(out, "{indent}if *budget == 0 {{").unwrap();
    writeln!(out, "{indent}    return Ok(Next::Halt);").unwrap();
    writeln!(out, "{indent}}}").unwrap();
}

fn indent(text: &str, spaces: usize) -> String {
    let prefix = " ".repeat(spaces);
    text.lines()
        .map(|line| format!("{prefix}{line}\n"))
        .collect()
}

pub(super) fn block_name(addr: u32, thumb: bool) -> String {
    format!("block_{addr:08x}_{}", if thumb { "thumb" } else { "arm" })
}
