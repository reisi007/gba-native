//! Deterministic metadata and the generated README for the WASM module build.
//!
//! The renderers take already-produced bytes instead of paths, so they are pure
//! and unit-testable without Cargo, wasm-bindgen or guest execution. Metadata is
//! ordered `key=value` and contains no absolute paths, timestamps or ROM bytes.

use std::fmt::Write as _;

use super::artifact::AotArtifact;
use super::target_build::{ToolchainFacts, build_metadata};
use super::wasm_build::WASM_TARGET;
use gba_native::sha256;

/// Render the WASM artifact metadata. `module` and `glue` are the produced
/// `_bg.wasm` and JS bindings, read only for hashing.
pub fn wasm_artifact_metadata(
    artifact: &AotArtifact,
    budget: u64,
    source: &str,
    module: &[u8],
    glue: &[u8],
    wasm_bindgen_version: &str,
) -> String {
    let mut out = String::new();
    writeln!(out, "schema=1").unwrap();
    writeln!(out, "artifact_kind=wasm-module").unwrap();
    writeln!(out, "target={WASM_TARGET}").unwrap();
    writeln!(out, "rom_sha256={}", artifact.rom_sha256_hex()).unwrap();
    writeln!(out, "rom_bytes={}", artifact.rom_len).unwrap();
    writeln!(out, "entry=0x{:08X}", artifact.entry).unwrap();
    writeln!(
        out,
        "entry_state={}",
        if artifact.entry_thumb { "thumb" } else { "arm" }
    )
    .unwrap();
    writeln!(out, "budget={budget}").unwrap();
    let stats = &artifact.stats;
    writeln!(out, "blocks={}", stats.blocks).unwrap();
    writeln!(out, "translated_instructions={}", stats.instructions).unwrap();
    writeln!(out, "resolved_bx={}", stats.resolved_bx).unwrap();
    writeln!(out, "dynamic_bx={}", stats.dynamic_bx).unwrap();
    writeln!(out, "bl_calls={}", stats.bl_calls).unwrap();
    writeln!(out, "bl_returns={}", stats.bl_returns).unwrap();
    writeln!(out, "dynamic_bl={}", stats.dynamic_bl).unwrap();
    writeln!(out, "pc_writes={}", stats.pc_writes).unwrap();
    writeln!(out, "swis={}", stats.swis).unwrap();
    writeln!(out, "decode_stops={}", stats.decode_stops).unwrap();
    writeln!(out, "external_targets={}", stats.external_targets).unwrap();
    writeln!(out, "block_limit_splits={}", stats.block_limit_splits).unwrap();
    writeln!(out, "limit_reached={}", stats.limit_reached).unwrap();
    writeln!(
        out,
        "program_source_sha256={}",
        sha256::hex(&sha256::digest(source.as_bytes()))
    )
    .unwrap();
    writeln!(out, "js_glue_sha256={}", sha256::hex(&sha256::digest(glue))).unwrap();
    writeln!(
        out,
        "module_sha256={}",
        sha256::hex(&sha256::digest(module))
    )
    .unwrap();
    writeln!(out, "wasm_bindgen_version={wasm_bindgen_version}").unwrap();
    writeln!(out, "embedded_rom_bytes=0").unwrap();
    writeln!(out, "requires_external_rom=true").unwrap();
    out
}

/// Render build metadata for the WASM build: the shared Cargo/rustc facts plus
/// the wasm-bindgen CLI pin.
pub fn wasm_build_metadata(facts: &ToolchainFacts, wasm_bindgen_version: &str) -> String {
    let mut out = build_metadata(WASM_TARGET, facts);
    writeln!(out, "wasm_bindgen_version={wasm_bindgen_version}").unwrap();
    out
}

/// Generated README for one owned WASM workspace. It documents the callable
/// module and the external-ROM contract; it never records a ROM filename.
pub fn wasm_readme(artifact: &AotArtifact, budget: u64) -> String {
    let mut out = String::new();
    out.push_str(
        "# ROM-bound WASM execution module (experimental prototype)\n\n\
         Generated by `gba-native aot build <rom.gba> --target wasm32-unknown-unknown`.\n\n\
         This directory is a browser-callable WebAssembly **execution module**, not an\n\
         HTML/JS application bundle. There is no app UI, GPU renderer, input handling,\n\
         save persistence or playable game here.\n\n\
         ## Binding\n\n",
    );
    writeln!(out, "- ROM SHA-256: `{}`", artifact.rom_sha256_hex()).unwrap();
    writeln!(out, "- ROM length: {} bytes", artifact.rom_len).unwrap();
    writeln!(
        out,
        "- Entry: 0x{:08X} ({})",
        artifact.entry,
        if artifact.entry_thumb { "Thumb" } else { "ARM" }
    )
    .unwrap();
    writeln!(out, "- Build-time instruction budget: {budget}").unwrap();
    out.push_str(
        "\nNo ROM bytes are embedded in this module or written by the build. The\n\
         caller supplies the image at call time and it must match the digest and\n\
         length above; a different image throws a JavaScript error before the\n\
         cartridge, CPU or bus is constructed.\n\n\
         ## JavaScript API\n\n\
         ```js\n\
         import init, { run_rom, run_rom_audio, audio_sample_rate }\n\
           from \"./pkg/gba_native_wasm_module.js\";\n\n\
         await init();\n\
         // `input` is a caller-provided <input type=\"file\"> element; this module\n\
         // generates no page UI and the selected file stays local to the browser.\n\
         const bytes = new Uint8Array(await input.files[0].arrayBuffer());\n\
         const report = run_rom(bytes); // Uint8Array -> compact key=value report\n\
         const pcm = run_rom_audio(bytes); // Int16Array of mono guest PCM\n\
         console.log(report, pcm.length, audio_sample_rate());\n\
         ```\n\n\
         The bytes come from a browser-local `File` selected by the user. Nothing is\n\
         fetched from a URL, uploaded to a server or written to disk: the ROM never\n\
         leaves the page, and this module never hosts or serves one.\n\n\
         `run_rom` copies the `Uint8Array` into WASM memory, verifies length and\n\
         SHA-256, initializes the direct-entry CPU, BIOS stacks and entry state, and\n\
         executes the build-time budget. On success it returns a compact report with\n\
         `pc`, `cpsr`, `thumb`, `budget`, `budget_remaining`, `budget_used`,\n\
         `fallbacks` and CPU/bus/ROM digests. Core failures are thrown as JS errors;\n\
         unsupported instructions or I/O are never silently ignored.\n\n\
         `run_rom_audio` runs the same bounded program with the stateful mixer and\n\
         returns mono signed 16-bit PCM at `audio_sample_rate()` (32768 Hz), mixing\n\
         PSG and Direct Sound FIFO playback from guest state. It performs no\n\
         playback, buffering or scheduling itself: the caller owns the WebAudio\n\
         sink. A run produces exactly the samples due inside its instruction budget;\n\
         that is not a track length or real-time guarantee.\n\n\
         ## Explicit non-claims\n\n\
         An exhausted instruction budget is not a frame, boot or playability claim.\n\
         This module has no browser UI, no GPU presentation, no game input, no saves\n\
         and no per-ROM application shell. Only the documented core subset and the\n\
         synthetic-fixture verification apply.\n",
    );
    out
}
