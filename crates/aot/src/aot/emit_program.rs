use std::fmt::Write as _;

use super::artifact::AotArtifact;
use super::emit::{block_name, emit_block};
use gba_native::cart::Cartridge;
use gba_native::error::{Error, Result};

/// Emit the target-neutral program section: translated block functions plus a
/// caller-driven dispatcher over caller-supplied CPU, bus and budget.
///
/// The section deliberately contains no host driver: no entry point, argument
/// parsing, file or path access, process control, stdout/stderr reporting, ROM
/// binding or ROM image bytes. The caller loads and binds the cartridge,
/// initializes the CPU and bus, selects the entry state and supplies the
/// instruction budget.
pub fn emit_program_module(cart: &Cartridge, artifact: &AotArtifact) -> Result<String> {
    artifact.verify(cart)?;
    if artifact.entry_thumb && !artifact.entry.is_multiple_of(2) {
        return Err(Error::Aot("unaligned Thumb entry".to_string()));
    }
    let mut out = String::new();
    writeln!(
        out,
        "// Generated by gba-native. Experimental prototype; do not edit."
    )
    .unwrap();
    writeln!(
        out,
        "// Target-neutral program section: translated blocks and a caller-driven dispatcher."
    )
    .unwrap();
    writeln!(
        out,
        "// The host driver owns arguments, file access, ROM binding and reporting."
    )
    .unwrap();
    writeln!(
        out,
        "#![allow(clippy::all, unused_variables, unreachable_code)]"
    )
    .unwrap();
    writeln!(out, "use gba_native::bus::Bus;").unwrap();
    writeln!(out, "use gba_native::cpu::Cpu;").unwrap();
    writeln!(out, "use gba_native::error::Result;").unwrap();
    writeln!(out, "use gba_native::interpret;").unwrap();
    writeln!(out, "use gba_native::ir::Cond;").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "pub const ENTRY: u32 = 0x{:08X};", artifact.entry).unwrap();
    writeln!(
        out,
        "pub const ENTRY_THUMB: bool = {};",
        artifact.entry_thumb
    )
    .unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#[derive(Clone, Copy, PartialEq, Eq)]").unwrap();
    writeln!(out, "enum Next {{ Continue, Halt }}").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "/// Runtime facts from one program run.").unwrap();
    writeln!(out, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]").unwrap();
    writeln!(out, "pub struct ProgramReport {{").unwrap();
    writeln!(out, "    pub budget_remaining: u64,").unwrap();
    writeln!(out, "    pub fallbacks: u64,").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    for block in &artifact.blocks {
        emit_block(&mut out, block)?;
    }
    emit_program_runner(&mut out, artifact);
    Ok(out)
}

/// Emit `run_program`, the target-neutral dispatch loop. It returns the
/// remaining budget and fallback count instead of printing or exiting.
fn emit_program_runner(out: &mut String, artifact: &AotArtifact) {
    writeln!(
        out,
        "/// Execute the program against an initialized CPU/bus until the budget is"
    )
    .unwrap();
    writeln!(
        out,
        "/// exhausted or a translated block halts. Unknown targets go through the"
    )
    .unwrap();
    writeln!(out, "/// reference interpreter with a fresh fetch/decode.").unwrap();
    writeln!(
        out,
        "pub fn run_program(cpu: &mut Cpu, bus: &mut Bus, budget: u64) -> Result<ProgramReport> {{"
    )
    .unwrap();
    writeln!(out, "    let mut remaining = budget;").unwrap();
    writeln!(out, "    let mut fallbacks = 0u64;").unwrap();
    writeln!(out, "    while remaining > 0 {{").unwrap();
    writeln!(out, "        let next = match (cpu.pc(), cpu.thumb()) {{").unwrap();
    for block in &artifact.blocks {
        writeln!(
            out,
            "            (0x{:08X}, {}) => {}(cpu, bus, &mut remaining)?,",
            block.addr,
            block.thumb,
            block_name(block.addr, block.thumb)
        )
        .unwrap();
    }
    writeln!(out, "            _ => {{").unwrap();
    writeln!(
        out,
        "                interpret::deliver_pending_irq(cpu, bus)?;"
    )
    .unwrap();
    writeln!(out, "                interpret::step(cpu, bus)?;").unwrap();
    writeln!(out, "                bus.tick_frame();").unwrap();
    writeln!(out, "                remaining -= 1;").unwrap();
    writeln!(out, "                fallbacks += 1;").unwrap();
    writeln!(out, "                Next::Continue").unwrap();
    writeln!(out, "            }}").unwrap();
    writeln!(out, "        }};").unwrap();
    writeln!(out, "        if next == Next::Halt {{").unwrap();
    writeln!(out, "            break;").unwrap();
    writeln!(out, "        }}").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "    Ok(ProgramReport {{").unwrap();
    writeln!(out, "        budget_remaining: remaining,").unwrap();
    writeln!(out, "        fallbacks,").unwrap();
    writeln!(out, "    }})").unwrap();
    writeln!(out, "}}").unwrap();
}
