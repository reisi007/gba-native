//! Instruction-budget timer model boundary tests.
//!
//! Every fixture is synthetic. Cycle expectations use the documented nominal
//! mapping of three cycles per retired guest instruction; they are not hardware
//! timing measurements.

use gba_native_core::bus::{Bus, INSTRUCTION_CYCLES};
use gba_native_core::cart::Cartridge;
use gba_native_core::cpu::{Cpu, FLAG_I};
use gba_native_core::interpret;
use gba_native_core::ir::{PSR_FIELD_C, Psr};

const TM0_L: u32 = 0x0400_0100;
const TM0_H: u32 = 0x0400_0102;
const TM1_L: u32 = 0x0400_0104;
const TM1_H: u32 = 0x0400_0106;
const TM2_L: u32 = 0x0400_0108;
const TM2_H: u32 = 0x0400_010A;
const TM3_H: u32 = 0x0400_010E;
const IE: u32 = 0x0400_0200;
const IF: u32 = 0x0400_0202;
const IME: u32 = 0x0400_0208;
const TIMER0_IRQ: u16 = 1 << 3;
const TIMER1_IRQ: u16 = 1 << 4;

fn bus() -> Bus {
    Bus::new(Cartridge::from_bytes(vec![0u8; 0x200]).expect("cartridge"))
}

fn read(bus: &Bus, addr: u32) -> u16 {
    bus.read16(addr).expect("timer register read")
}

fn write(bus: &mut Bus, addr: u32, value: u16) {
    bus.write16(addr, value).expect("timer register write");
}

#[test]
fn reload_write_is_latched_without_changing_the_stopped_counter() {
    let mut bus = bus();
    write(&mut bus, TM0_L, 0x0100);
    assert_eq!(read(&bus, TM0_L), 0, "the counter is not the reload latch");
    assert_eq!(read(&bus, TM0_H), 0);

    bus.tick_frames(10);
    assert_eq!(read(&bus, TM0_L), 0, "a stopped timer does not advance");

    write(&mut bus, TM0_H, 0x0080);
    assert_eq!(read(&bus, TM0_L), 0x0100, "the start edge reloads");
    bus.tick_frame();
    assert_eq!(
        read(&bus, TM0_L),
        0x0103,
        "one instruction contributes three F/1 cycles"
    );

    write(&mut bus, TM0_L, 0x0200);
    assert_eq!(
        read(&bus, TM0_L),
        0x0103,
        "a reload write never rewrites the running counter"
    );

    write(&mut bus, TM0_H, 0);
    assert_eq!(read(&bus, TM0_L), 0x0103, "disable freezes the counter");
    bus.tick_frames(5);
    assert_eq!(read(&bus, TM0_L), 0x0103);

    write(&mut bus, TM0_H, 0x0080);
    assert_eq!(read(&bus, TM0_L), 0x0200, "re-enable reloads the new value");
}

#[test]
fn simultaneous_reload_and_start_uses_the_written_reload_value() {
    let mut bus = bus();
    // 32-bit I/O is composed from two halfwords: reload first, control second.
    bus.write32(TM0_L, 0x0080_0200).expect("combined write");
    assert_eq!(read(&bus, TM0_L), 0x0200);
    bus.tick_frame();
    assert_eq!(read(&bus, TM0_L), 0x0203);
}

#[test]
fn prescaler_selections_follow_the_nominal_instruction_clock() {
    // F/1: every three-cycle instruction advances the counter three times.
    let mut f1 = bus();
    write(&mut f1, TM0_H, 0x0080);
    f1.tick_frame();
    assert_eq!(read(&f1, TM0_L), 3);
    f1.tick_frame();
    assert_eq!(read(&f1, TM0_L), 6);

    // F/64: 21 instructions are 63 cycles and still below the divisor.
    let mut f64 = bus();
    write(&mut f64, TM0_H, 0x0081);
    f64.tick_frames(21);
    assert_eq!(read(&f64, TM0_L), 0, "63 of 64 cycles");
    f64.tick_frame();
    assert_eq!(read(&f64, TM0_L), 1, "66 cycles cross one divisor");

    // F/256: 85 instructions are 255 cycles.
    let mut f256 = bus();
    write(&mut f256, TM0_H, 0x0082);
    f256.tick_frames(85);
    assert_eq!(read(&f256, TM0_L), 0, "255 of 256 cycles");
    f256.tick_frame();
    assert_eq!(read(&f256, TM0_L), 1);

    // F/1024: 341 instructions are 1023 cycles.
    let mut f1024 = bus();
    write(&mut f1024, TM0_H, 0x0083);
    f1024.tick_frames(341);
    assert_eq!(read(&f1024, TM0_L), 0, "1023 of 1024 cycles");
    f1024.tick_frame();
    assert_eq!(read(&f1024, TM0_L), 1);
}

#[test]
fn overflow_reloads_and_latches_only_enabled_timer_requests() {
    let mut bus = bus();
    write(&mut bus, TM0_L, 0xFFFD);
    write(&mut bus, TM0_H, 0x00C0); // start + timer IRQ
    assert_eq!(read(&bus, IF), 0);

    bus.tick_frame();
    assert_eq!(
        read(&bus, TM0_L),
        0xFFFD,
        "one overflow reloads the latch value"
    );
    assert_eq!(read(&bus, IF) & TIMER0_IRQ, TIMER0_IRQ);

    write(&mut bus, IF, TIMER0_IRQ);
    assert_eq!(read(&bus, IF) & TIMER0_IRQ, 0, "IF is write-one-to-clear");

    // Clearing the IRQ-enable bit does not stop the timer; it only suppresses
    // the request generated by later overflows.
    write(&mut bus, TM0_H, 0x0080);
    bus.tick_frame();
    assert_eq!(read(&bus, IF) & TIMER0_IRQ, 0);
}

#[test]
fn timer_request_still_requires_ie_and_ime_for_dispatch() {
    let mut bus = bus();
    write(&mut bus, TM0_L, 0xFFFF);
    write(&mut bus, TM0_H, 0x00C0);
    write(&mut bus, IE, TIMER0_IRQ);
    assert!(!bus.irq_pending(), "IME is still disabled");
    write(&mut bus, IME, 1);
    bus.tick_frame();
    assert!(bus.irq_pending(), "overflow request is deliverable");
    write(&mut bus, IF, TIMER0_IRQ);
    assert!(!bus.irq_pending(), "acknowledged request is gone");
}

#[test]
fn count_up_timer_ignores_its_prescaler_and_follows_previous_overflow() {
    let mut bus = bus();
    write(&mut bus, TM0_L, 0xFFFF);
    write(&mut bus, TM0_H, 0x0080); // F/1, no request
    write(&mut bus, TM1_L, 0);
    write(&mut bus, TM1_H, 0x0087); // start + count-up + F/1024
    bus.tick_frame();
    assert_eq!(
        read(&bus, TM1_L),
        3,
        "three Timer 0 overflows despite Timer 1's F/1024 bits"
    );
    bus.tick_frame();
    assert_eq!(read(&bus, TM1_L), 6);
}

#[test]
fn cascaded_overflow_chains_through_consecutive_timers() {
    let mut bus = bus();
    write(&mut bus, TM0_L, 0xFFFF);
    write(&mut bus, TM0_H, 0x0080);
    write(&mut bus, TM1_L, 0xFFFF);
    write(&mut bus, TM1_H, 0x0084); // start + count-up
    write(&mut bus, TM2_L, 0);
    write(&mut bus, TM2_H, 0x0084);
    bus.tick_frame();
    assert_eq!(read(&bus, TM2_L), 3, "three chained overflows");
}

#[test]
fn a_disabled_previous_timer_never_advances_a_cascaded_timer() {
    let mut bus = bus();
    write(&mut bus, TM1_L, 0);
    write(&mut bus, TM1_H, 0x0084);
    bus.tick_frames(100);
    assert_eq!(read(&bus, TM1_L), 0);

    write(&mut bus, TM0_H, 0x0080);
    write(&mut bus, TM0_L, 0);
    bus.tick_frames(100);
    assert_eq!(
        read(&bus, TM1_L),
        0,
        "Timer 0 incremented but did not overflow"
    );
}

#[test]
fn timer0_count_up_bit_is_documented_unused_and_ignored() {
    let mut bus = bus();
    write(&mut bus, TM0_L, 0x0100);
    write(&mut bus, TM0_H, 0x00C4); // start + IRQ + unused count-up bit
    assert_eq!(
        read(&bus, TM0_H),
        0x00C0,
        "Timer 0's count-up bit reads back as zero"
    );
    bus.tick_frame();
    assert_eq!(
        read(&bus, TM0_L),
        0x0103,
        "the timer still runs as a normal F/1 counter"
    );

    // A standard 32-bit reload+control write is two ordinary halfword writes;
    // the unused bit in the high half is ignored rather than failing the write.
    write(&mut bus, TM0_H, 0); // stop so the combined write has a start edge
    bus.write32(TM0_L, 0x0084_0200).expect("combined write");
    assert_eq!(read(&bus, TM0_H), 0x0080);
    assert_eq!(read(&bus, TM0_L), 0x0200, "the start edge reloads");
    bus.tick_frame();
    assert_eq!(read(&bus, TM0_L), 0x0203);

    // Timer 1..3 do have a previous timer, so the same bit is meaningful there.
    write(&mut bus, TM1_H, 0x0084);
    assert_eq!(read(&bus, TM1_H), 0x0084);
}

#[test]
fn cascaded_overflow_raises_the_cascaded_timers_irq() {
    let mut bus = bus();
    write(&mut bus, TM0_L, 0xFFFF);
    write(&mut bus, TM0_H, 0x00C0); // start + Timer 0 IRQ
    write(&mut bus, TM1_L, 0xFFFF);
    write(&mut bus, TM1_H, 0x00C4); // start + count-up + Timer 1 IRQ
    write(&mut bus, IE, TIMER0_IRQ | TIMER1_IRQ);
    write(&mut bus, IME, 1);
    bus.tick_frame();
    assert_eq!(
        read(&bus, IF) & TIMER0_IRQ,
        TIMER0_IRQ,
        "the source timer's own overflow request is latched"
    );
    assert_eq!(
        read(&bus, IF) & TIMER1_IRQ,
        TIMER1_IRQ,
        "the cascaded timer's overflow request is latched too"
    );
    assert!(bus.irq_pending(), "the cascaded request is deliverable");
}

#[test]
fn running_prescaler_and_count_up_changes_discard_partial_phase() {
    // F/64 has accumulated 63 cycles without an increment.
    let mut prescaler = bus();
    write(&mut prescaler, TM0_L, 0x0100);
    write(&mut prescaler, TM0_H, 0x0081); // start, F/64
    prescaler.tick_frames(21);
    assert_eq!(read(&prescaler, TM0_L), 0x0100);
    write(&mut prescaler, TM0_H, 0x0083); // still running, F/1024
    assert_eq!(
        read(&prescaler, TM0_L),
        0x0100,
        "a clock-source change keeps the counter"
    );
    prescaler.tick_frames(341); // 1023 cycles: would have incremented if phase carried
    assert_eq!(
        read(&prescaler, TM0_L),
        0x0100,
        "the old F/64 phase must not carry into F/1024"
    );
    prescaler.tick_frame();
    assert_eq!(read(&prescaler, TM0_L), 0x0101);

    // A running normal timer switches to count-up with a 63-cycle phase.
    let mut count_up = bus();
    write(&mut count_up, TM1_L, 0x0100);
    write(&mut count_up, TM1_H, 0x0081); // start, F/64
    count_up.tick_frames(21);
    assert_eq!(read(&count_up, TM1_L), 0x0100);
    write(&mut count_up, TM1_H, 0x0084); // still running, count-up
    assert_eq!(
        read(&count_up, TM1_L),
        0x0100,
        "a count-up change keeps the counter"
    );
    count_up.tick_frames(100);
    assert_eq!(
        read(&count_up, TM1_L),
        0x0100,
        "count-up ignores both its prescaler and the discarded phase"
    );
    write(&mut count_up, TM0_L, 0xFFFF);
    write(&mut count_up, TM0_H, 0x0080);
    count_up.tick_frame();
    assert_eq!(
        read(&count_up, TM1_L),
        0x0103,
        "three previous-timer overflows now advance the cascaded timer"
    );
}

#[test]
fn reserved_control_bits_read_as_zero() {
    let mut bus = bus();
    write(&mut bus, TM0_H, 0xFFFB); // all bits except count-up
    assert_eq!(read(&bus, TM0_H), 0x00C3);
    write(&mut bus, TM3_H, 0xFFFF);
    assert_eq!(read(&bus, TM3_H), 0x00C7);
}

#[test]
fn batch_and_single_instruction_ticks_are_equivalent_with_timers_running() {
    let counts = [0, 1, 21, 22, 341, 342, 1000];
    for count in counts {
        let mut batched = bus();
        for (low, high, control) in [
            (TM0_L, TM0_H, 0x00C0),
            (TM1_L, TM1_H, 0x0084),
            (TM2_L, TM2_H, 0x00C0),
        ] {
            write(&mut batched, low, 0xFFFD);
            write(&mut batched, high, control);
        }
        batched.tick_frames(count);

        let mut single = bus();
        for (low, high, control) in [
            (TM0_L, TM0_H, 0x00C0),
            (TM1_L, TM1_H, 0x0084),
            (TM2_L, TM2_H, 0x00C0),
        ] {
            write(&mut single, low, 0xFFFD);
            write(&mut single, high, control);
        }
        for _ in 0..count {
            single.tick_frame();
        }

        assert_eq!(
            batched.state_digest(),
            single.state_digest(),
            "batch of {count} instructions"
        );
        for addr in [TM0_L, TM1_L, TM2_L, IF] {
            assert_eq!(read(&batched, addr), read(&single, addr), "{addr:#010x}");
        }
    }
}

#[test]
fn register_ram_reset_group_seven_clears_timer_state() {
    let mut bus = bus();
    write(&mut bus, TM0_L, 0x1234);
    write(&mut bus, TM0_H, 0x00C0);
    bus.tick_frames(5);
    assert_ne!(read(&bus, TM0_L), 0);
    bus.reset_group7_io();
    assert_eq!(read(&bus, TM0_L), 0);
    assert_eq!(read(&bus, TM0_H), 0);
    assert_eq!(read(&bus, IF) & TIMER0_IRQ, 0);
}

#[test]
fn timer_overflow_request_reaches_the_existing_irq_dispatcher() {
    const ENTRY: u32 = 0x0800_0000;
    const HANDLER: u32 = 0x0800_0100;
    let mut rom = vec![0u8; 0x200];
    rom[..2].copy_from_slice(&0xE7FEu16.to_le_bytes());
    rom[0x100..0x104].copy_from_slice(&0xE12F_FF1Eu32.to_le_bytes());
    let mut bus = Bus::new(Cartridge::from_bytes(rom).expect("IRQ fixture"));
    bus.write32(0x0300_7FFC, HANDLER).expect("handler pointer");
    write(&mut bus, IE, TIMER0_IRQ);
    write(&mut bus, IME, 1);
    write(&mut bus, TM0_L, 0xFFFF);
    write(&mut bus, TM0_H, 0x00C0);
    bus.tick_frame();
    assert!(bus.irq_pending(), "timer overflow is a deliverable request");

    let mut cpu = Cpu::direct_entry();
    cpu.initialize_bios_stacks();
    cpu.set_pc(ENTRY);
    cpu.set_thumb(true);
    cpu.write_psr(Psr::Cpsr, PSR_FIELD_C, cpu.cpsr() & !FLAG_I)
        .expect("unmask IRQ");
    assert!(interpret::deliver_pending_irq(&mut cpu, &mut bus).expect("delivery"));
    assert_eq!(cpu.pc(), HANDLER);
    assert_eq!(read(&bus, IF) & TIMER0_IRQ, TIMER0_IRQ);
}

#[test]
fn nominal_frame_budget_still_matches_the_documented_cycle_total() {
    assert_eq!(
        gba_native_core::bus::FRAME_INSTRUCTIONS * u64::from(INSTRUCTION_CYCLES),
        280_896
    );
    // Timer requests use IF bits 3..6, leaving the VBlank bit untouched.
    assert_ne!(TIMER0_IRQ, 1);
    assert_ne!(TIMER1_IRQ, 1);
}
